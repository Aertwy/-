class House:
    def __new__(cls, *args, **kwargs):
        print("__new__:分配内存，造房子")

        obj = object.__new__(cls)
        return obj
    def __init__(self,name,age):
        print("__init__:初始化对象，给对象属性赋值，装修房子")
        self.name=name
        self.age=age

house=House(1,3)

















# ================================================================
#  __new__ 与 __init__ 对比速查表
# ================================================================
#
#  一、核心作用
#  --------------------------------------------------------------
#  __new__  : 创建对象，分配内存（造房子）
#  __init__ : 初始化对象，设置属性（装修房子）
#
#  二、第一个参数
#  --------------------------------------------------------------
#  __new__(cls, ...)   : cls  —— 代表当前类
#  __init__(self, ...) : self —— 代表当前对象（实例）
#
#  三、返回值
#  --------------------------------------------------------------
#  __new__  : 必须返回对象引用（不返回 → __init__ 不执行，实例为 None）
#  __init__ : 无返回值，默认 None（不能 return 非 None 值）
#
#  四、执行时机
#  --------------------------------------------------------------
#  __new__  : 实例化时先执行
#  __init__ : 在 __new__ 之后执行
#
#  记忆口诀：先造房（__new__）→ 再装修（__init__）
# ================================================================

















































