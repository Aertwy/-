# ================================================================
#  正则表达式（re 模块）速查表
# ================================================================
#
#  〇、导入模块
#  import re
#
#  一、常用元字符（匹配符号）
#  --------------------------------------------------------------
#  .        第一一个字符（换行符除外）
#  \d       数字 0-9               \D     非数字
#  \w       字母、数字、下划线、中文  \W     非 \w
#  \s       空白（空格、\t、\n）     \S     非空白
#  ^        字符串开头               $      字符串结尾
#  *        后面的字符出现 0 次或多次
#  +        后面的字符出现 1 次或多次
#  ?        后面的字符出现 0 次或 1 次
#  {m}      正好 m 次                {m,n}  m 到 n 次
#  [abc]    匹配 num、b、c 中任意一个
#  [^abc]   不是 num、b、c 的任意一个
#  [num-z]    小写字母范围；[0-9] 数字范围
#  |        或（左边或右边都行）
#  ()       分组（括起来整体重复 / 提取）
#  \b       单词边界
#  转义：\. 表示真的点，\\ 表示真的反斜杠
#
#  二、常用函数
#  --------------------------------------------------------------
#  re.match(正则, 字符串)     从字符串“开头”匹配，开头不符合就返回 None
#  re.search(正则, 字符串)    在“任意位置”找第一个匹配（最常用）
#  re.findall(正则, 字符串)   找出所有匹配，返回列表
#  re.finditer(正则, 字符串)  同 findall，但返回迭代器（省内存）
#  re.fullmatch(正则, 字符串) 整个字符串必须完全匹配（做校验用）
#  re.sub(正则, 新内容, 字符串) 把匹配到的全部替换掉
#  re.split(正则, 字符串)     按匹配到的内容切分字符串
#  re.compile(正则)           先编译好正则，反复使用更快
#
#  三、常用成品表达式（可直接抄）
#  --------------------------------------------------------------
#  手机号     1[3-9]\d{9}
#  邮箱       [\w.-]+@[\w-]+(\.[\w-]+)+
#  身份证     \d{17}[\dXx]
#  中文       [\u4e00-\u9fa5]+
#  IP地址     \d{1,3}(\.\d{1,3}){3}
#  提取所有数字 \d+
#
#  四、三条铁律
#  --------------------------------------------------------------
#  1. 写正则一律用 r 前缀：r"\d+"（和路径的 r 一个道理，防止 \ 被转义）
#  2. 贪婪 vs 非贪婪：.* 吃得越多越好；.*? 吃得越少越好
#  3. 要匹配 . * + ? ( ) 等特殊字符本身，必须加 \ 转义
# ================================================================






























































