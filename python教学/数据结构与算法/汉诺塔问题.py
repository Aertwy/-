#有A,B,C三根圆柱,A柱上有若干个大小不同的圆盘，开始时所有圆盘按照从大到小的顺序叠放，最大的在最下面，
#最小的在最上面。
#现在需要将 A 柱上的所有圆盘移动到 C 柱。
#======================================
"""每次只能移动一个圆盘。
每次只能取柱子最上面的圆盘。
大圆盘不能放在小圆盘上面。
可以利用 B 柱作为辅助。
最终所有圆盘必须从 A 柱移动到 C 柱。"""

def hanoi(n,start,middle,end):
    if n == 1:
        #起始柱移动到终点柱
        print(f"{start} -> {end}")
        return
    #2. 那么n-1的就应该移动到上一个的中间柱上给最后一个盘子让路，因为最后的盘子要在最底下
            #开始柱   结束柱   中间柱
    hanoi(n-1, start, end, middle)
    #A-C-B
    #将n从初始柱移动到结束柱
    print(f"{start} -> {end}")
    #3. 然后将n-1移动到C也就是n的结束柱
    hanoi(n-1, middle, start, end)
    #B-A-C
#1. 先是圆盘的数量为n，初始柱为A，中间柱为B，结束柱为C
hanoi(4, "A", "B", "C")
